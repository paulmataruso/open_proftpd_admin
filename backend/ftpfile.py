"""
Generates ProFTPd virtual user files:

  ftpd.passwd       — authentication for all users (regular + trusted)
  ftpd_trusted.conf — <IfUser> blocks that give trusted users their own chroot + R/W access
  ftpd_private.conf — chroot + R/W for private users under PRIVATE_FTP_BASE_PATH, plus a
                      deny-all on that base and a per-folder AllowUser lock

Format per ftpd.passwd line:
  username:hashed_password:uid:gid:gecos:home_dir:shell

Regular users:  home_dir = /   (chrooted to global FTP root by DefaultRoot in proftpd.conf)
Trusted users:  home_dir = FTP_BASE_PATH/<ftp_home_dir>  (chrooted by <IfUser> block)
Private users:  home_dir = PRIVATE_FTP_BASE_PATH/<ftp_home_dir>  (chrooted by group DefaultRoot ~)
"""

import os
import stat
from sqlalchemy.orm import Session
from config import settings
from models import User, TrustedFtpUser, PrivateFtpUser


def regenerate_ftpd_passwd(db: Session) -> int:
    """Write ftpd.passwd for all enabled users (regular + trusted + private). Returns total count written."""
    users   = db.query(User).filter(User.enabled == True).order_by(User.username).all()
    trusted = db.query(TrustedFtpUser).filter(TrustedFtpUser.enabled == True).order_by(TrustedFtpUser.username).all()
    private = _enabled_private(db)

    lines = []
    for u in users:
        lines.append(
            f"{u.username}:{u.password_hash}:"
            f"{settings.ftp_uid}:{settings.ftp_gid}:"
            f"FTP User {u.username}:/:/sbin/nologin"
        )
    for u in trusted:
        home = f"{settings.ftp_base_path}/{u.ftp_home_dir}"
        lines.append(
            f"{u.username}:{u.password_hash}:"
            f"{settings.ftp_uid}:{settings.trusted_ftp_gid}:"
            f"Trusted FTP User {u.username}:{home}:/sbin/nologin"
        )

    for u in private:
        home = private_home(u)
        lines.append(
            f"{u.username}:{u.password_hash}:"
            f"{settings.ftp_uid}:{settings.private_ftp_gid}:"
            f"Private FTP User {u.username}:{home}:/sbin/nologin"
        )

    content = "\n".join(lines) + ("\n" if lines else "")
    _atomic_write(settings.ftpd_passwd_path, content)
    return len(users) + len(trusted) + len(private)


def regenerate_ftpd_trusted_conf(db: Session) -> int:
    """Write ftpd_trusted.conf with <IfUser> chroot blocks for enabled trusted users."""
    trusted = db.query(TrustedFtpUser).filter(TrustedFtpUser.enabled == True).order_by(TrustedFtpUser.username).all()

    lines = ["# Auto-generated by ciosuseradd — do not edit manually", ""]
    for u in trusted:
        home = f"{settings.ftp_base_path}/{u.ftp_home_dir}"
        lines += [
            f"<IfUser {u.username}>",
            f"  DefaultRoot {home}",
            f"  <Directory {home}>",
            f"    AllowOverwrite on",
            f"    <Limit STOR APPE MKD XMKD DELE RNFR RNTO RMD XRMD>",
            f"      AllowAll",
            f"    </Limit>",
            f"  </Directory>",
            f"</IfUser>",
            "",
        ]

    _atomic_write(settings.ftpd_trusted_conf_path, "\n".join(lines))
    return len(trusted)


def private_home(u: PrivateFtpUser) -> str:
    return f"{settings.private_ftp_base_path.rstrip('/')}/{u.ftp_home_dir}"


def _enabled_private(db: Session) -> list:
    return db.query(PrivateFtpUser).filter(PrivateFtpUser.enabled == True).order_by(PrivateFtpUser.username).all()


def regenerate_ftpd_private_conf(db: Session) -> int:
    """Write ftpd_private.conf: group chroot, deny-all on the private base, per-user R/W.

    The chroot can't come from an <IfUser> block: mod_ifsession merges those only
    after mod_auth has already chrooted, so DefaultRoot there is ignored (trusted
    users get away with it because their homes sit inside the global DefaultRoot).
    Instead every private user gets PRIVATE_FTP_GID, and `DefaultRoot ~ <group>`
    chroots members to their ftpd.passwd home at login.

    Each home folder is also locked to its owner with AllowUser/DenyAll, and
    Umask 027 keeps uploads unreadable to other local accounts.
    """
    private = _enabled_private(db)
    base = settings.private_ftp_base_path.rstrip("/")

    lines = [
        "# Auto-generated by ciosuseradd — do not edit manually",
        "",
        f"DefaultRoot ~ {settings.private_ftp_group}",
        "",
        f"<Directory {base}>",
        f"  <Limit ALL>",
        f"    DenyAll",
        f"  </Limit>",
        f"</Directory>",
        "",
    ]
    for u in private:
        home = private_home(u)
        lines += [
            f"<Directory {home}>",
            f"  AllowOverwrite on",
            f"  Umask 027 027",
            f"  <Limit ALL>",
            f"    AllowUser {u.username}",
            f"    DenyAll",
            f"  </Limit>",
            f"</Directory>",
            "",
        ]

    _atomic_write(settings.ftpd_private_conf_path, "\n".join(lines))
    return len(private)


def _atomic_write(path: str, content: str) -> None:
    # Skip identical rewrites: the host's ciosuseradd-proftpd-reload.path unit
    # reloads ProFTPd whenever ftpd_trusted.conf / ftpd_private.conf change, and
    # sync() runs on every user mutation, most of which don't touch these files.
    try:
        with open(path) as f:
            if f.read() == content:
                return
    except FileNotFoundError:
        pass
    tmp = path + ".tmp"
    with open(tmp, "w") as f:
        f.write(content)
    os.chmod(tmp, stat.S_IRUSR | stat.S_IWUSR | stat.S_IRGRP)
    os.rename(tmp, path)
